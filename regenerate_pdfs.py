#!/usr/bin/env python3
"""
Regenerate PDFs for the notebooks in this folder, and (re)configure Jupyter/
nbconvert so that Cyrillic text renders correctly in PDF exports.

Designed to be dropped into a fresh checkout of this course folder on any
machine (Windows/macOS/Linux) and just run:

    python3 regenerate_pdfs.py

What it does, every time it runs:
  1. Checks that xelatex and Jupyter/nbconvert are available (prints install
     instructions per OS and stops if something required is missing).
  2. Picks the best available Cyrillic-capable fonts on this machine.
  3. Installs a small nbconvert template ("ukr_pdf") that layers Cyrillic
     fonts, long-line wrapping in code cells, and emoji stripping (the emoji
     used as decorative header markers in these notebooks don't exist in
     regular LaTeX text fonts and would otherwise show up as tofu boxes) on
     top of nbconvert's stock LaTeX template.
  4. Points nbconvert's default config at that template, so BOTH
     `jupyter nbconvert --to pdf ...` on the command line AND Jupyter
     Notebook/Lab's own "Save and Export Notebook As -> PDF" menu use it
     automatically, without extra flags.
  5. Regenerates a PDF for every *.ipynb in this folder.

Steps 1-4 are idempotent (safe to re-run) and only touch your Jupyter user
profile (config dir / data dir) - never anything inside this project folder.
Skip them with --skip-setup once a machine is already configured.

Usage:
    python3 regenerate_pdfs.py                  # configure Jupyter + export all notebooks here
    python3 regenerate_pdfs.py --setup-only      # only install the template/config, don't export
    python3 regenerate_pdfs.py --skip-setup      # only export, assume setup already done
    python3 regenerate_pdfs.py a.ipynb b.ipynb   # export only these notebooks (paths relative to CWD)
    python3 regenerate_pdfs.py --check           # report what would happen, change nothing
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import textwrap
from pathlib import Path

TEMPLATE_NAME = "ukr_pdf"
TEMPLATE_ENTRY = "uk_report.tex.j2"
PREPROCESSOR_MODULE = "strip_emoji_preprocessor"
PREPROCESSOR_CLASS = "StripEmojiPreprocessor"
CONFIG_MARK_BEGIN = f"# >>> ukr_pdf cyrillic-pdf-export config (autogenerated) >>>"
CONFIG_MARK_END = f"# <<< ukr_pdf cyrillic-pdf-export config (autogenerated) <<<"
CONFIG_FILES = (
    "jupyter_nbconvert_config.py",
    "jupyter_server_config.py",
    "jupyter_config.py",
)

# Preference order; the first one actually installed on the machine wins.
FONT_CANDIDATES = {
    "main": ["DejaVu Serif", "Noto Serif", "Liberation Serif", "PT Serif"],
    "sans": ["DejaVu Sans", "Noto Sans", "Liberation Sans", "PT Sans"],
    "mono": ["DejaVu Sans Mono", "Noto Sans Mono", "Liberation Mono", "PT Mono"],
}


def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def have(cmd: str) -> bool:
    return shutil.which(cmd) is not None


def jupyter_path(kind: str) -> Path:
    """kind: 'data-dir' or 'config-dir'"""
    for py in (sys.executable, "python3", "python"):
        out = run([py, "-m", "jupyter_core", "--" + kind])
        if out.returncode == 0 and out.stdout.strip():
            return Path(out.stdout.strip())
    out = run(["jupyter", "--" + kind])
    if out.returncode == 0 and out.stdout.strip():
        return Path(out.stdout.strip())
    raise RuntimeError(
        f"Could not determine Jupyter {kind}. Is Jupyter installed and on PATH?"
    )


def fc_list_families() -> set[str]:
    if not have("fc-list"):
        return set()
    out = run(["fc-list", "--format=%{family}\n"])
    fams: set[str] = set()
    for line in out.stdout.splitlines():
        for name in line.split(","):
            name = name.strip()
            if name:
                fams.add(name)
    return fams


def pick_fonts() -> dict[str, str]:
    available = fc_list_families()
    chosen = {}
    for role, candidates in FONT_CANDIDATES.items():
        pick = next((c for c in candidates if c in available), None)
        if pick is None:
            pick = candidates[0]  # best-effort fallback; user may need to install it
            if available:
                print(
                    f"  [warn] none of {candidates} found via fc-list; "
                    f"defaulting to '{pick}' for {role} font - install it if PDF export fails."
                )
        chosen[role] = pick
    return chosen


def check_prerequisites() -> list[str]:
    problems = []
    if not have("jupyter"):
        problems.append(
            "`jupyter` not found on PATH.\n"
            "    Install with: pip install jupyter nbconvert"
        )
    if not have("xelatex"):
        problems.append(
            "`xelatex` not found on PATH. A full LaTeX distribution is required for PDF export.\n"
            "    Debian/Ubuntu: sudo apt install texlive-xetex texlive-latex-extra texlive-fonts-recommended fonts-dejavu\n"
            "    Fedora:        sudo dnf install texlive-xetex texlive-collection-latexextra dejavu-sans-fonts\n"
            "    macOS:         brew install --cask mactex-no-gui   (or the full MacTeX)\n"
            "    Windows:       install MiKTeX (miktex.org) or TeX Live, and let it auto-install packages on first use"
        )
    elif not have("kpsewhich"):
        problems.append("`kpsewhich` not found - unusual for a TeX install, but LaTeX package availability can't be checked.")
    else:
        needed_packages = {
            "fvextra": "needed to wrap long lines in code cells",
            "xurl": "needed to wrap long URLs instead of overflowing the page margin",
            "mdframed": "needed to draw the boxes around code listings and self-check sections",
            "fancyhdr": "needed for running page headers/footers (title/author byline)",
        }
        for pkg, why in needed_packages.items():
            out = run(["kpsewhich", f"{pkg}.sty"])
            if out.returncode != 0 or not out.stdout.strip():
                problems.append(
                    f"LaTeX package `{pkg}` not found ({why}).\n"
                    "    Debian/Ubuntu: sudo apt install texlive-latex-extra\n"
                    "    Fedora:        sudo dnf install texlive-collection-latexextra\n"
                    f"    MiKTeX/MacTeX: usually installs it automatically on first use; if not, use its package manager to install '{pkg}'"
                )
    return problems


PREPROCESSOR_SOURCE = '''\
"""Strip decorative pictographic emoji from cell source before LaTeX/PDF
rendering. Regular LaTeX text fonts (DejaVu, Noto, Liberation, ...) don't
contain emoji glyphs, so left in place they render as empty "tofu" boxes.
The notebooks themselves keep their emoji untouched - this only applies to
the PDF/LaTeX export path. Meaningful symbols (arrows, dashes, No sign, ...)
are intentionally left alone.
"""
import re
from nbconvert.preprocessors import Preprocessor

_EMOJI_RE = re.compile(
    "["
    "\\U0001F000-\\U0001FFFF"
    "\\U00002600-\\U000027BF"
    "\\U0001F1E6-\\U0001F1FF"
    "\\U0000FE00-\\U0000FE0F"
    "\\U000020E3"
    "\\U0000200D"
    "]+"
)


class StripEmojiPreprocessor(Preprocessor):
    def preprocess_cell(self, cell, resources, index):
        if "source" in cell and cell.source:
            cleaned = _EMOJI_RE.sub("", cell.source)
            cleaned = re.sub(r"[ \\t]+\\n", "\\n", cleaned)
            cell.source = cleaned
        return cell, resources
'''


def template_source(fonts: dict[str, str]) -> str:
    return textwrap.dedent(
        f"""\
        ((*- extends 'index.tex.j2' -*))

        ((* block packages *))
            ((( super() )))
            % --- Cyrillic support: fonts with full Cyrillic coverage ---
            \\setmainfont{{{fonts['main']}}}
            \\setsansfont{{{fonts['sans']}}}
            \\setmonofont{{{fonts['mono']}}}
            % --- Wrap long lines in code cells instead of overflowing the page ---
            \\usepackage{{fvextra}}
            \\fvset{{breaklines=true, breakanywhere=true}}
            % --- Allow long URLs/links to break at (almost) any character
            %     instead of overflowing the page margin; load after hyperref ---
            \\usepackage{{xurl}}
            % --- Running page headers/footers (title/author byline, page
            %     numbers). Loaded here so it's available to every notebook,
            %     but NOT activated (no \\pagestyle{{fancy}}/\\fancyhead calls) -
            %     that stays notebook-specific, set via a raw-latex front-matter
            %     cell in the notebook itself (mirrors the titlepage/TOC
            %     pattern), so notebooks that don't opt in keep plain pages. ---
            \\usepackage{{fancyhdr}}
            \\setlength{{\\headheight}}{{14pt}}
            % --- Boxes for code listings and self-check sections ---
            \\usepackage{{mdframed}}
            \\definecolor{{codeboxbg}}{{HTML}}{{F5F7FA}}
            \\definecolor{{codeboxborder}}{{HTML}}{{C9DCEC}}
            \\definecolor{{selfcheckboxbg}}{{HTML}}{{ECFDF5}}
            \\definecolor{{selfcheckboxborder}}{{HTML}}{{0D9488}}
            % Reusable box style for a titled definition-style box (self-check
            % sections wrap themselves in \\begin{{selfcheckbox}}/\\end{{selfcheckbox}}
            % via a pair of raw-latex notebook cells sandwiching the section).
            \\newmdenv[
                backgroundcolor=selfcheckboxbg,
                linecolor=selfcheckboxborder,
                linewidth=0.6pt,
                roundcorner=3pt,
                innermargin=8pt,
                outermargin=0pt,
                innertopmargin=8pt,
                innerbottommargin=8pt,
                skipabove=10pt,
                skipbelow=10pt,
            ]{{selfcheckbox}}
        ((* endblock packages *))

        % --- Suppress nbconvert's default \\maketitle (filename + export date).
        %     Notebooks that want a real titlepage build one themselves as a
        %     raw-latex front-matter cell instead. ---
        ((* block maketitle *))((* endblock maketitle *))

        % --- Box every fenced code listing (pandoc's "Shaded" environment,
        %     normally a no-op wrapper) in a light bordered box, so MicroPython
        %     examples read as distinct listings rather than blending into prose.
        %     Must come AFTER the base template's own \\newenvironment{{Shaded}}{{}}{{}}
        %     (defined in its "definitions" block, which closes before "commands"
        %     opens), so this has to be a "commands" override, not "packages". ---
        ((* block commands *))
            ((( super() )))
            \\renewenvironment{{Shaded}}{{%
              \\begin{{mdframed}}[
                backgroundcolor=codeboxbg,
                linecolor=codeboxborder,
                linewidth=0.6pt,
                roundcorner=3pt,
                innermargin=6pt,
                outermargin=0pt,
                innertopmargin=6pt,
                innerbottommargin=6pt,
                skipabove=8pt,
                skipbelow=8pt,
              ]
            }}{{%
              \\end{{mdframed}}
            }}
            % --- Start each numbered chapter (the notebook's "# 📘 Розділ N."
            %     headings, which compile to \\section) on a fresh page, like a
            %     book's \\chapter would. \\section* (starred - used for the
            %     unnumbered title/foreword/TOC headings) is untouched. ---
            \\let\\ukroldsection\\section
            \\renewcommand{{\\section}}{{\\clearpage\\ukroldsection}}
            % --- The base template's hyperref linkcolor (an orange/rust,
            %     rgb .71,.21,.01) colors every internal link, including every
            %     TOC entry - looks out of place in a print book, so redefine
            %     it here (after hypersetup already ran) to plain black; links
            %     stay clickable on-screen, just not visually colored. ---
            \\definecolor{{linkcolor}}{{HTML}}{{000000}}
            \\hypersetup{{linkcolor=linkcolor}}
        ((* endblock commands *))
        """
    )


def install_template(fonts: dict[str, str], check_only: bool) -> Path:
    data_dir = jupyter_path("data-dir")
    tmpl_dir = data_dir / "nbconvert" / "templates" / TEMPLATE_NAME
    print(f"  template dir: {tmpl_dir}")
    if check_only:
        return tmpl_dir
    tmpl_dir.mkdir(parents=True, exist_ok=True)

    conf = {
        "base_template": "latex",
        "mimetypes": {"text/latex": True, "text/tex": True, "application/pdf": True},
    }
    (tmpl_dir / "conf.json").write_text(json.dumps(conf, indent=2), encoding="utf-8")
    (tmpl_dir / TEMPLATE_ENTRY).write_text(template_source(fonts), encoding="utf-8")
    (tmpl_dir / f"{PREPROCESSOR_MODULE}.py").write_text(PREPROCESSOR_SOURCE, encoding="utf-8")
    return tmpl_dir


def config_block(tmpl_dir: Path) -> str:
    tmpl_dir_repr = repr(str(tmpl_dir))
    return f"""{CONFIG_MARK_BEGIN}
import sys as _ukr_sys
_ukr_tmpl_dir = {tmpl_dir_repr}
if _ukr_tmpl_dir not in _ukr_sys.path:
    _ukr_sys.path.insert(0, _ukr_tmpl_dir)

for _ukr_cls in ("PDFExporter", "LatexExporter"):
    getattr(c, _ukr_cls).template_name = "{TEMPLATE_NAME}"
    getattr(c, _ukr_cls).template_file = "{TEMPLATE_ENTRY}"
    getattr(c, _ukr_cls).preprocessors = [
        "{PREPROCESSOR_MODULE}.{PREPROCESSOR_CLASS}",
        "nbconvert.preprocessors.TagRemovePreprocessor",
    ]

# Cells tagged "remove_input" (e.g. diagram-generating code whose source is
# irrelevant to the reader - only the rendered figure output matters) have
# their input hidden but their output kept. Untagged code cells (e.g. the
# lab notebooks' actual example code) are unaffected.
c.TagRemovePreprocessor.remove_input_tags = {{"remove_input"}}
c.TagRemovePreprocessor.enabled = True
{CONFIG_MARK_END}
"""


def install_config(tmpl_dir: Path, check_only: bool) -> Path:
    config_dir = jupyter_path("config-dir")
    print(f"  config dir:   {config_dir}")
    block = config_block(tmpl_dir)
    if not check_only:
        config_dir.mkdir(parents=True, exist_ok=True)
    for fname in CONFIG_FILES:
        path = config_dir / fname
        existing = path.read_text(encoding="utf-8") if path.exists() else ""
        if CONFIG_MARK_BEGIN in existing:
            # Replace the existing autogenerated block in place (idempotent re-run).
            pattern = re.compile(
                re.escape(CONFIG_MARK_BEGIN) + r".*?" + re.escape(CONFIG_MARK_END) + r"\n?",
                re.DOTALL,
            )
            new_content = pattern.sub(block, existing)
            action = "updated"
        else:
            sep = "" if not existing or existing.endswith("\n") else "\n"
            new_content = existing + sep + "\n" + block
            action = "created" if not existing else "appended to"
        if check_only:
            print(f"    would be {action}: {path}")
        else:
            path.write_text(new_content, encoding="utf-8")
            print(f"    {action}: {path}")
    return config_dir


def setup_cyrillic_pdf_export(check_only: bool = False) -> bool:
    print("== Checking prerequisites ==")
    problems = check_prerequisites()
    if problems:
        print("Missing prerequisites - install these first, then re-run this script:\n")
        for p in problems:
            print(f"  - {p}\n")
        return False
    print("  OK: jupyter, xelatex, fvextra all found.\n")

    print("== Picking Cyrillic-capable fonts ==")
    fonts = pick_fonts()
    for role, name in fonts.items():
        print(f"  {role}: {name}")
    print()

    print("== Installing nbconvert template ==")
    tmpl_dir = install_template(fonts, check_only)
    print()

    print("== Wiring up Jupyter config (CLI + 'Export as PDF' menu) ==")
    install_config(tmpl_dir, check_only)
    print()
    return True


def find_notebooks(explicit, folder: Path) -> list[Path]:
    if explicit:
        return [Path(p) for p in explicit]
    notebooks = sorted(
        p for p in folder.glob("*.ipynb") if ".ipynb_checkpoints" not in p.parts
    )
    return notebooks


def export_pdf(nb_path: Path, out_dir: Path) -> tuple[bool, str]:
    cmd = [
        sys.executable, "-m", "jupyter", "nbconvert", "--to", "pdf",
        str(nb_path), "--output-dir", str(out_dir),
    ]
    result = run(cmd)
    ok = result.returncode == 0 and (out_dir / (nb_path.stem + ".pdf")).exists()
    log = result.stderr if not ok else ""
    return ok, log


def regenerate_pdfs(notebooks: list[Path], out_dir: Path) -> int:
    if not notebooks:
        print("No notebooks found to export.")
        return 1
    print(f"== Exporting {len(notebooks)} notebook(s) to PDF ==")
    failures = []
    for nb in notebooks:
        print(f"  {nb.name} ... ", end="", flush=True)
        ok, log = export_pdf(nb, out_dir)
        if ok:
            print("done")
        else:
            print("FAILED")
            failures.append((nb, log))
    if failures:
        print(f"\n{len(failures)} notebook(s) failed:")
        for nb, log in failures:
            print(f"\n--- {nb.name} ---")
            print(log[-2000:] if log else "(no error output captured)")
        return 1
    print("\nAll notebooks exported successfully.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("notebooks", nargs="*", help="specific .ipynb files to export (default: all in this folder)")
    parser.add_argument("--setup-only", action="store_true", help="only configure Jupyter, don't export PDFs")
    parser.add_argument("--skip-setup", action="store_true", help="only export PDFs, assume setup already done")
    parser.add_argument("--check", action="store_true", help="report what would happen, change nothing")
    args = parser.parse_args()

    script_dir = Path(__file__).resolve().parent

    if not args.skip_setup:
        ok = setup_cyrillic_pdf_export(check_only=args.check)
        if not ok:
            return 1

    if args.setup_only or args.check:
        return 0

    notebooks = find_notebooks(args.notebooks, script_dir)
    return regenerate_pdfs(notebooks, script_dir)


if __name__ == "__main__":
    raise SystemExit(main())
